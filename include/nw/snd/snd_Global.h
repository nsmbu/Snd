struct OutputParam
{
    f32 volume;
    f32 pan;
    f32 span;
    f32 mainSend;
    f32 fxSend[AUX_BUS_NUM];

    void Initialize()
    {
        volume = 1.0f;
        pan = 0.0f;
        span = 0.0f;
        mainSend = 0.0f;
        for (int i = 0; i < AUX_BUS_NUM; i++)
            fxSend[i] = 0.0f;
    };
};
static_assert(sizeof(OutputParam) == 0x1C);

struct RemoteOutputParam
{
    f32 volume;
    f32 mainSend;
    f32 fxSend;

    void Initialize()
    {
        volume = 1.0f;
        mainSend = 0.0f;
        fxSend = 0.0f;
    }
};
static_assert(sizeof(RemoteOutputParam) == 0xC);

